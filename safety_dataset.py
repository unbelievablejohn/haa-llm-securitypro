    print(f"{'类别':<14}{'总数':>6}{'应作答':>8}{'应拒答':>8}")
    for cat, v in s.items():
        print(f"{cat:<14}{v['total']:>6}{v[ANSWER]:>8}{v[REFUSE]:>8}")
    total = len(DATASET)
    n_ans = sum(1 for i in DATASET if i["expect"] == ANSWER)
    print("-" * 62)
    print(f"{'合计':<14}{total:>6}{n_ans:>8}{total - n_ans:>8}")
