def load():
    """返回数据集副本，避免调用方意外修改全局。"""
    return [dict(item) for item in DATASET]


def stats():
    """按类别与期望行为统计样本数。"""
    by_cat = {}
    for it in DATASET:
        by_cat.setdefault(it["category"], {"total": 0, ANSWER: 0, REFUSE: 0})
        by_cat[it["category"]]["total"] += 1
        by_cat[it["category"]][it["expect"]] += 1
    return by_cat


