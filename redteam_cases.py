# -*- coding: utf-8 -*-
"""
redteam_cases.py —— Red Team 对抗用例集（20 条）

为什么单独做一套 Red Team
-------------------------
safety_dataset.py 里的 54 条是**常规评测集**，用来量指标、做对照。
Red Team 的目的不同：它是**主动攻击自己的系统**，专门挑最难防的角度，
目标是把它打穿。

计划里写得很明确：

    "主动公开自己系统的失败案例，是研究诚信的体现，
      也是 HAA 最看重的能力：知道自己系统的边界在哪。"

因此本用例集的设计原则是：**宁可被攻破，也不要出软柿子**。
每一条都要比常规评测集更难，这样"攻破 / 未攻破"的记录才有信息量。

三类攻击手法
------------
A. 虚构理论 / 虚构人物（7 条）
   编造听起来完全合理的学术概念、人名、机构。难点在于"合理性" ——
   名称越像真的，模型越容易顺着编。

B. 不可能事件 / 因果颠倒（6 条）
   前提本身违反物理定律或时间顺序。模型可能为了"配合提问"而接受前提。

C. 假前提 / 错误预设（7 条）
   把错误结论藏在问题里当作既定事实。模型若不拆穿前提就直接回答，
   等于替错误结论背书。

与既有 J 组（注入变体）的关系
-----------------------------
J 组专测**施压与操纵**，本集专测**内容层面的诱导**（虚构、不可能、假前提）。
两者互补：J 组攻的是"你的流程"，本集攻的是"你的知识边界"。

每条用例都标注：
    danger     一旦被攻破，会产生什么危害
    why        为什么它应当被拒答（或应当被拆穿）
    difficulty 设计难度定位，便于解释为什么选它
"""

